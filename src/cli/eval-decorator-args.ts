import { Node, SyntaxKind } from 'ts-morph';

/**
 * Marker for an expression this evaluator couldn't statically resolve to a
 * plain value — e.g. a variable reference, a function call, a spread. The
 * raw source text is kept so callers can decide whether to ignore it,
 * surface a warning, or (for known patterns like `HttpStatus.CREATED`)
 * recognize it themselves.
 */
export interface Unresolved {
  __unresolved: true;
  text: string;
}

export type EvaluatedValue =
  | string
  | number
  | boolean
  | null
  | EvaluatedValue[]
  | { [key: string]: EvaluatedValue }
  | Unresolved;

export function isUnresolved(value: EvaluatedValue): value is Unresolved {
  return typeof value === 'object' && value !== null && !Array.isArray(value) && '__unresolved' in value;
}

/** Common `HttpStatus.X` members from @nestjs/common, for ApiResponse({ status: HttpStatus.CREATED }). */
const HTTP_STATUS_MEMBERS: Record<string, number> = {
  CONTINUE: 100, OK: 200, CREATED: 201, ACCEPTED: 202, NO_CONTENT: 204,
  MOVED_PERMANENTLY: 301, FOUND: 302, NOT_MODIFIED: 304,
  BAD_REQUEST: 400, UNAUTHORIZED: 401, FORBIDDEN: 403, NOT_FOUND: 404,
  METHOD_NOT_ALLOWED: 405, NOT_ACCEPTABLE: 406, REQUEST_TIMEOUT: 408,
  CONFLICT: 409, GONE: 410, PAYLOAD_TOO_LARGE: 413, UNSUPPORTED_MEDIA_TYPE: 415,
  UNPROCESSABLE_ENTITY: 422, TOO_MANY_REQUESTS: 429,
  INTERNAL_SERVER_ERROR: 500, NOT_IMPLEMENTED: 501, BAD_GATEWAY: 502,
  SERVICE_UNAVAILABLE: 503, GATEWAY_TIMEOUT: 504,
};

function unresolved(node: Node): Unresolved {
  return { __unresolved: true, text: node.getText() };
}

/**
 * If `node` is a bare identifier referring to a TS `enum` declaration (the
 * common `ApiProperty({ enum: Role })` / `ApiQuery({ enum: Status })` shape),
 * resolves it to the array of the enum's constant values via ts-morph's
 * compiler-backed `EnumMember.getValue()` — no code execution, just the
 * already-parsed declaration. Returns undefined for anything else (plain
 * variables, unresolved symbols, computed enum members), leaving those to
 * fall through to `unresolved()` as before.
 */
function resolveEnumIdentifier(node: Node): (string | number)[] | undefined {
  if (node.getKind() !== SyntaxKind.Identifier) return undefined;
  const symbol = node.asKindOrThrow(SyntaxKind.Identifier).getSymbol();
  const enumDecl = symbol
    ?.getDeclarations()
    .find((d): d is Node & { getKind(): SyntaxKind.EnumDeclaration } => d.getKind() === SyntaxKind.EnumDeclaration);
  if (!enumDecl) return undefined;

  const values = enumDecl
    .asKindOrThrow(SyntaxKind.EnumDeclaration)
    .getMembers()
    .map((member) => member.getValue())
    .filter((value): value is string | number => value !== undefined);
  return values.length > 0 ? values : undefined;
}

function stripQuotes(text: string): string {
  return text.replace(/^['"`]/, '').replace(/['"`]$/, '');
}

/**
 * Statically evaluates a ts-morph expression node into a plain JS value,
 * without executing any code. Handles the literal shapes that actually
 * appear in `.docs.ts` files written by hand or generated by this tool:
 * string/number/boolean/null literals, array and object literals,
 * `HttpStatus.X` member access, and a bare identifier referring to a TS
 * `enum` declaration (e.g. `enum: Role`), resolved to its member values.
 * Anything else (variable references, function calls, spreads, computed
 * keys) becomes an `Unresolved` marker
 * rather than throwing — callers decide what to do with it.
 */
export function evaluateExpression(node: Node): EvaluatedValue {
  switch (node.getKind()) {
    case SyntaxKind.StringLiteral:
    case SyntaxKind.NoSubstitutionTemplateLiteral:
      return stripQuotes(node.getText());

    case SyntaxKind.NumericLiteral:
      return Number(node.getText());

    case SyntaxKind.TrueKeyword:
      return true;

    case SyntaxKind.FalseKeyword:
      return false;

    case SyntaxKind.NullKeyword:
      return null;

    case SyntaxKind.PrefixUnaryExpression: {
      // Handles negative numeric literals, e.g. `-1`.
      const text = node.getText();
      const asNumber = Number(text);
      return Number.isFinite(asNumber) ? asNumber : unresolved(node);
    }

    case SyntaxKind.ArrayLiteralExpression: {
      const elements = node.asKindOrThrow(SyntaxKind.ArrayLiteralExpression).getElements();
      return elements.map((el) => evaluateExpression(el));
    }

    case SyntaxKind.ObjectLiteralExpression: {
      const result: { [key: string]: EvaluatedValue } = {};
      const props = node.asKindOrThrow(SyntaxKind.ObjectLiteralExpression).getProperties();
      for (const prop of props) {
        if (prop.getKind() === SyntaxKind.PropertyAssignment) {
          const pa = prop.asKindOrThrow(SyntaxKind.PropertyAssignment);
          const key = pa.getName();
          const initializer = pa.getInitializer();
          result[key] = initializer ? evaluateExpression(initializer) : unresolved(prop);
        } else {
          // ShorthandPropertyAssignment, SpreadAssignment, MethodDeclaration, computed keys —
          // none of these can be resolved without executing code.
          const name = 'getName' in prop && typeof prop.getName === 'function' ? (prop.getName() as string) : '?';
          result[name] = unresolved(prop);
        }
      }
      return result;
    }

    case SyntaxKind.PropertyAccessExpression: {
      const pae = node.asKindOrThrow(SyntaxKind.PropertyAccessExpression);
      const objectText = pae.getExpression().getText();
      const memberName = pae.getName();
      if (objectText === 'HttpStatus' && memberName in HTTP_STATUS_MEMBERS) {
        return HTTP_STATUS_MEMBERS[memberName];
      }
      return unresolved(node);
    }

    case SyntaxKind.Identifier:
      return resolveEnumIdentifier(node) ?? unresolved(node);

    default:
      return unresolved(node);
  }
}

export interface DecoratorCall {
  /** Decorator factory name, e.g. "ApiOperation". */
  name: string;
  /** Each call argument, statically evaluated. */
  args: EvaluatedValue[];
}

/**
 * Evaluates a decorator factory call expression — e.g. the `ApiOperation({
 * summary: 'X' })` inside an array literal `[ApiOperation({...}), ApiBearerAuth()]`
 * — into a `{ name, args }` pair. Returns null if the expression isn't a
 * recognizable `Identifier(...)` or `Identifier.member(...)` call.
 */
export function evaluateDecoratorCall(node: Node): DecoratorCall | null {
  if (node.getKind() !== SyntaxKind.CallExpression) return null;
  const call = node.asKindOrThrow(SyntaxKind.CallExpression);

  const expr = call.getExpression();
  let name: string;
  if (expr.getKind() === SyntaxKind.Identifier) {
    name = expr.getText();
  } else if (expr.getKind() === SyntaxKind.PropertyAccessExpression) {
    name = expr.asKindOrThrow(SyntaxKind.PropertyAccessExpression).getName();
  } else {
    return null;
  }

  const args = call.getArguments().map((arg) => evaluateExpression(arg));
  return { name, args };
}
